static const glyph *find_glyph(char c) {
    for (size_t i = 0; i < sizeof(FONT) / sizeof(FONT[0]); i++)
        if (FONT[i].c == c) return &FONT[i];
    return NULL;
}

bool glyph_pixel(char c, int gx, int gy) {
    const glyph *g = find_glyph(c);
    return g && gx >= 0 && gx < 5 && gy >= 0 && gy < 7 && g->rows[gy][gx] == '#';
}

int text_width(const char *s, int scale) { return (int)strlen(s) * 6 * scale - scale; }

void draw_text(const char *s, int x, int y, int scale, px color) {
    for (int ci = 0; s[ci]; ci++)
        for (int gy = 0; gy < 7; gy++)
            for (int gx = 0; gx < 5; gx++)
                if (glyph_pixel(s[ci], gx, gy))
                    fill_rect(x + ci * 6 * scale + gx * scale, y + gy * scale, scale, scale, color);
}

void draw_text_shadow(const char *s, int x, int y, int scale, px color) {
    draw_text(s, x + scale, y + scale, scale, C_BLACK);
    draw_text(s, x, y, scale, color);
}

void draw_text_centered(const char *s, int y, int scale, px color) {
    draw_text_shadow(s, (W - text_width(s, scale)) / 2, y, scale, color);
}

// ---------------------------------------------------------------------------
// RNG (xorshift32)
// ---------------------------------------------------------------------------

static uint32_t rng_state = 0x4c0a7a1u;

void rng_seed(uint32_t seed) { rng_state ^= seed ? seed : 1; }

uint32_t rnd(void) {
    uint32_t x = rng_state;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    return rng_state = x;
}

int rrange(int lo, int hi) { return lo + (int)(rnd() % (uint32_t)(hi - lo)); }
