#include "gfx.h"

#include <string.h>

px fb[H][W];

void put(int x, int y, px c) {
    if ((unsigned)x < W && (unsigned)y < H) fb[y][x] = c;
}

void fill_rect(int x, int y, int w, int h, px c) {
    for (int j = y; j < y + h; j++)
        for (int i = x; i < x + w; i++) put(i, j, c);
}

void fill_circle(int cx, int cy, int r, px c) {
    for (int dy = -r; dy <= r; dy++)
        for (int dx = -r; dx <= r; dx++)
            if (dx * dx + dy * dy <= r * r) put(cx + dx, cy + dy, c);
}

void fade_framebuffer(float level) {
    if (level >= 1) return;
    int k = level <= 0 ? 0 : (int)(level * 256);
    for (int y = 0; y < H; y++)
        for (int x = 0; x < W; x++) {
            px c = fb[y][x];
            fb[y][x] = ((((c >> 16) & 255) * k >> 8) << 16) | ((((c >> 8) & 255) * k >> 8) << 8) | ((c & 255) * k >> 8);
        }
}

void pal_set(palette *p, char ch, px c) {
    p->c[(int)ch] = c;
    p->on[(int)ch] = true;
}

void draw_sprite(const char **rows, int nrows, int x, int y, bool flip, const palette *p) {
    for (int j = 0; j < nrows; j++) {
        int len = (int)strlen(rows[j]);
        for (int i = 0; i < len; i++) {
            unsigned char ch = (unsigned char)rows[j][i];
            if (ch < 128 && p->on[ch]) put(flip ? x + len - 1 - i : x + i, y + j, p->c[ch]);
        }
    }
}

